const DICTS: Record<Lang, Dict> = { en, zh, es, fr };

export type Vars = Record<string, string | number | undefined>;

export function translate(lang: Lang, key: string, vars?: Vars): string {
  const raw = DICTS[lang][key] ?? en[key] ?? key;
  if (!vars) return raw;
  return raw.replace(/\{(\w+)\}/g, (_, k) => (vars[k] === undefined ? "" : String(vars[k])));
}

export type T = (key: string, vars?: Vars) => string;

export function makeT(lang: Lang): T {
  return (key, vars) => translate(lang, key, vars);
}

export function listJoin(lang: Lang, items: string[]): string {
  return items.join(translate(lang, "common.list"));
}

export function tagLabel(lang: Lang, t: TagId): string {
  return translate(lang, `tag.${t}`);
}

export function tagList(lang: Lang, tags: TagId[] | string): string {
  const arr = (typeof tags === "string" ? tags.split(",").filter(Boolean) : tags) as TagId[];
  return listJoin(lang, arr.map((t) => tagLabel(lang, t)));
}

export function styleLabel(lang: Lang, s: GuideStyle): string {
  return translate(lang, `style.${s}`);
}

export function detailLabel(lang: Lang, d: DetailLevel): string {
  return translate(lang, `detail.${d}`);
}

/** Render a translatable code. Tag lists (comma-separated ids) and detail levels are localised. */
export function renderCode(lang: Lang, c: Code): string {
  const v: Vars = { ...(c.v ?? {}) };
  if (typeof v.tags === "string") v.tags = tagList(lang, v.tags);
  if (typeof v.level === "number") v.level = detailLabel(lang, v.level as DetailLevel);
  return translate(lang, c.k, v);
}

export function renderWhy(lang: Lang, w: Why): string {
  const parts: string[] = [];
  if (w.must) parts.push(translate(lang, "why.must"));
  if (w.note) parts.push(translate(lang, "why.note"));
  if (w.matched.length) parts.push(translate(lang, "why.matched", { tags: tagList(lang, w.matched) }));
  if (w.liked.length) parts.push(translate(lang, "why.liked", { tags: tagList(lang, w.liked) }));
  if (w.filler) parts.push(translate(lang, `why.${w.filler}`));
  return parts.join(" ");
}
